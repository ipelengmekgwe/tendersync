/// <summary>
/// Development and e2e aid (Worker <c>--seed-demo</c>): one demo tender with a three-page PDF bid pack, its extracted text,
/// requirements whose sources point at pages 2 and 3, a qualification report and a New match for the active company
/// profile (a demo profile is created only when there is none). Rerunning resets the match to New with no notes,
/// moves the closing date forward when it is near, and restores anything missing. Domain events are cleared before the
/// save, so nothing is classified, notified or queued. The ocid is not on eTenders; the daily refresh counts it as gone.
/// A second tender, <see cref="KeywordBidNumber"/>, is a Goods tender about "quokka" feed that no seeded keyword matches;
/// each run clears its classification and matches, so the category e2e test (add "quokka" as a keyword → reclassify →
/// a match appears) starts from the same place every time.
/// </summary>
public sealed class DemoDataSeeder(AppDbContext context, IDocumentStore store, IDateTimeProvider clock, ILogger<DemoDataSeeder> logger)
{
    public const string DemoOcid = "ocds-tendersync-demo-0001";
    public const string DemoBidNumber = "DEMO/E2E/0001";
    public const string DemoBuyerExternalId = "tendersync-demo";
    public const string KeywordOcid = "ocds-tendersync-demo-0002";
    public const string KeywordBidNumber = "DEMO/E2E/0002";

    /// <summary>A word only the keyword demo tender contains.</summary>
    public const string KeywordDemoWord = "quokka";
    private const string Model = "demo-seed";
    private const string PromptVersion = "demo";

    /// <summary>The text of each PDF page; requirement sources quote these lines.</summary>
    public static IReadOnlyList<string> PageTexts { get; } =
    [
        "TENDERSYNC DEMO MUNICIPALITY\nBID NUMBER DEMO/E2E/0001\n\nAppointment of a service provider for network support and\nmanaged IT services for a period of 36 months.\n\nCompulsory briefing session: Civic Centre, Room 4, 10:00.\n\nThis document is demo data generated by TenderSync.",
        "SECTION 2: MANDATORY REQUIREMENTS\n\n2.1 Bidders must be registered on the Central Supplier Database (CSD).\n2.2 Bidders must submit a valid tax compliance status PIN.\n2.3 Only B-BBEE Level 1 to 4 contributors will be considered.\n2.4 The bidder must have at least 5 years of experience in network support.\n\nFailure to comply with any mandatory requirement will lead to disqualification.",
        "SECTION 3: FUNCTIONALITY AND RETURNABLE DOCUMENTS\n\n3.1 Experience of key personnel: 30 points.\n3.2 Methodology and project plan: 40 points.\n3.3 Contactable references for similar work: 30 points.\nMinimum functionality threshold: 70 points out of 100.\n\n3.4 Completed and signed SBD 4 (Bidder's Disclosure) must be returned.",
    ];

    public async Task<DemoSeedResult> SeedAsync(CancellationToken cancellationToken = default)
    {
        var now = clock.UtcNow;

        var profile = await context.CompanyProfileSet.Where(p => p.IsActive).OrderBy(p => p.CreatedAt).FirstOrDefaultAsync(cancellationToken);
        var profileCreated = profile is null;
        if (profile is null)
        {
            profile = DemoProfile(now);
            context.CompanyProfileSet.Add(profile);
        }

        var buyer = await context.BuyerSet.FirstOrDefaultAsync(b => b.ExternalId == DemoBuyerExternalId, cancellationToken);
        if (buyer is null)
        {
            buyer = Buyer.Create(DemoBuyerExternalId, "TenderSync Demo Municipality", BuyerType.Municipal, Province.Gauteng);
            context.BuyerSet.Add(buyer);
        }

        var tender = await context.TenderSet.Include(t => t.Documents).Include(t => t.Releases).Include(t => t.StatusHistory)
            .AsSplitQuery().FirstOrDefaultAsync(t => t.Ocid == DemoOcid, cancellationToken);
        if (tender is null)
        {
            tender = Tender.CreateFromSnapshot(Snapshot(now, 1), buyer.Id, Province.Gauteng, TenderSourceKind.ETendersOcds, now);
            context.TenderSet.Add(tender);
        }
        else if (tender.ClosingAt is null || tender.ClosingAt < now.AddDays(5))
        {
            tender.ApplyRelease(Snapshot(now, tender.Releases.Count + 1), Province.Gauteng, now);
        }

        tender.SetSummary("Demo tender: network support and managed IT services for 36 months. Bidders need CSD registration, a valid tax PIN, B-BBEE level 1 to 4 and five years of network support experience; functionality is scored out of 100 with a 70-point threshold.");
        tender.SetBriefing(tender.ClosingAt?.AddDays(-5), true, "Civic Centre, Room 4");
        tender.SetSubmissionMethod(SubmissionMethod.ETendersOnline);
        tender.DeriveStatus(now);

        var document = tender.Documents.Single();
        var storagePath = $"tenders/{DemoOcid}/{document.Id}.pdf";
        if (document.StoragePath is null || !await store.ExistsAsync(document.StoragePath, cancellationToken))
        {
            var pdf = BuildPdf();
            using (var stream = new MemoryStream(pdf, writable: false))
            {
                storagePath = await store.SaveAsync(storagePath, stream, "application/pdf", cancellationToken);
            }

            document.MarkDownloaded(storagePath, Convert.ToHexStringLower(SHA256.HashData(pdf)), pdf.Length, now);
            document.MarkExtracted(PageTexts.Count, needsOcr: false, now);
            await context.DocumentTextSet.Where(t => t.DocumentId == document.Id).ExecuteDeleteAsync(cancellationToken);
            context.DocumentTextSet.AddRange(PageTexts.Select((text, i) => new DocumentText(document.Id, i + 1, text)));
        }

        if (!await context.TenderRequirementSet.AnyAsync(r => r.TenderId == tender.Id, cancellationToken))
        {
            context.TenderRequirementSet.AddRange(Requirements(tender.Id, document.Id, now));
        }

        var classification = await context.TenderClassificationSet.FirstOrDefaultAsync(c => c.TenderId == tender.Id, cancellationToken);
        if (classification is null)
        {
            context.TenderClassificationSet.Add(TenderClassification.Keyword(tender.Id, ["APP_SUPPORT", "IT_CONSULT"], 82, "Demo data: network support and managed IT services.", now));
        }

        if (!await context.QualificationReportSet.AnyAsync(r => r.TenderId == tender.Id && r.CompanyProfileId == profile.Id, cancellationToken))
        {
            context.QualificationReportSet.Add(Report(tender.Id, profile.Id, now));
        }

        var match = await context.TenderMatchSet.FirstOrDefaultAsync(m => m.TenderId == tender.Id && m.CompanyProfileId == profile.Id, cancellationToken);
        if (match is null)
        {
            match = TenderMatch.Create(tender.Id, profile.Id, 82, now);
            context.TenderMatchSet.Add(match);
        }
        else
        {
            match.SetStatus(MatchStatus.New);
            match.SetNotes(null);
        }

        var keywordTender = await SeedKeywordTenderAsync(buyer, now, cancellationToken);

        // Demo rows must not reach the pipeline: no TenderFirstSeen classification, no NewMatch notification.
        foreach (var entry in context.ChangeTracker.Entries<Entity>())
        {
            entry.Entity.ClearDomainEvents();
        }

        await context.SaveChangesAsync(cancellationToken);
        logger.LogInformation("Demo data ready: tender {Ocid} ({TenderId}), match {MatchId} for profile {ProfileId}", DemoOcid, tender.Id, match.Id, profile.Id);
        return new DemoSeedResult(tender.Id, match.Id, profile.Id, document.Id, profileCreated, keywordTender.Id);
    }

    private async Task<Tender> SeedKeywordTenderAsync(Buyer buyer, DateTimeOffset now, CancellationToken cancellationToken)
    {
        var tender = await context.TenderSet.Include(t => t.Documents).Include(t => t.Releases).Include(t => t.StatusHistory)
            .AsSplitQuery().FirstOrDefaultAsync(t => t.Ocid == KeywordOcid, cancellationToken);
        var closing = new DateTimeOffset(now.ToOffset(TimeSpan.FromHours(2)).Date.AddDays(21).AddHours(11), TimeSpan.FromHours(2)).ToUniversalTime();
        TenderSnapshot Snapshot(int release) => new(
            KeywordOcid, "demo-0002", KeywordBidNumber, "Supply of quokka feed pellets for the municipal sanctuary (demo)",
            "Supply of quokka feed pellets to the municipal wildlife sanctuary for twelve months. Demo data generated by TenderSync.",
            DemoBuyerExternalId, "TenderSync Demo Municipality", ProcurementCategory.Goods, ["goods"], "open", "Request for Quotation",
            null, "ZAR", now.AddDays(-1), closing, "https://www.etenders.gov.za/", $"{KeywordOcid}-r{release}", now, "tender", "{}", [], HasAwards: false);

        if (tender is null)
        {
            tender = Tender.CreateFromSnapshot(Snapshot(1), buyer.Id, Province.Gauteng, TenderSourceKind.ETendersOcds, now);
            context.TenderSet.Add(tender);
        }
        else if (tender.ClosingAt is null || tender.ClosingAt < now.AddDays(5))
        {
            tender.ApplyRelease(Snapshot(tender.Releases.Count + 1), Province.Gauteng, now);
        }

        tender.DeriveStatus(now);
        await context.TenderMatchSet.Where(m => m.TenderId == tender.Id).ExecuteDeleteAsync(cancellationToken);
        await context.TenderClassificationSet.Where(c => c.TenderId == tender.Id).ExecuteDeleteAsync(cancellationToken);
        return tender;
    }

    /// <summary>A three-page A4 PDF with <see cref="PageTexts"/>, one line per text line.</summary>
    public static byte[] BuildPdf()
    {
        var builder = new PdfDocumentBuilder();
        var font = builder.AddStandard14Font(Standard14Font.Helvetica);
        foreach (var text in PageTexts)
        {
            var page = builder.AddPage(UglyToad.PdfPig.Content.PageSize.A4);
            var y = 800.0;
            foreach (var line in text.Split('\n'))
            {
                if (line.Length > 0)
                {
                    page.AddText(line, 12, new PdfPoint(50, y), font);
                }

                y -= 18;
            }
        }

        return builder.Build();
    }

    private static TenderSnapshot Snapshot(DateTimeOffset now, int release)
    {
        var closing = new DateTimeOffset(now.ToOffset(TimeSpan.FromHours(2)).Date.AddDays(14).AddHours(11), TimeSpan.FromHours(2)).ToUniversalTime();
        return new TenderSnapshot(
            DemoOcid, "demo-0001", DemoBidNumber, "Network support and managed IT services (demo)",
            "Appointment of a service provider for network support and managed IT services for a period of 36 months. Demo data generated by TenderSync.",
            DemoBuyerExternalId, "TenderSync Demo Municipality", ProcurementCategory.Services, ["services"], "open", "Request for Bid (Open-Tender)",
            null, "ZAR", now.AddDays(-2), closing, "https://www.etenders.gov.za/", $"{DemoOcid}-r{release}", now, "tender", "{}",
            [new TenderDocumentSnapshot($"{DemoOcid}-bid-pack", "Bid Document DEMO-E2E-0001.pdf", "https://www.etenders.gov.za/", "pdf", "en", now.AddDays(-2), now.AddDays(-2))],
            HasAwards: false);
    }

    private static CompanyProfile DemoProfile(DateTimeOffset now)
    {
        var profile = CompanyProfile.Create("Demo Technologies (Pty) Ltd");
