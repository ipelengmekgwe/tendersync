import type { NextConfig } from "next";

/**
 * Headers on every response (docs/security-review.md, F7). The CSP limits framing, base URLs, form targets and plugins
 * but not scripts: Next's inline bootstrap scripts and the pdf.js worker would need nonces first. HSTS is added by the
 * middleware, which knows whether the request came over HTTPS.
 */
const securityHeaders = [
  { key: "Content-Security-Policy", value: "frame-ancestors 'none'; base-uri 'self'; form-action 'self'; object-src 'none'" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "Referrer-Policy", value: "same-origin" },
  { key: "Permissions-Policy", value: "camera=(), microphone=(), geolocation=(), payment=()" },
];

const nextConfig: NextConfig = {
  output: "standalone",
  reactStrictMode: true,
  poweredByHeader: false,
  async headers() {
    return [{ source: "/:path*", headers: securityHeaders }];
  },
};

export default nextConfig;
